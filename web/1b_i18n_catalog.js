(function buildCatalog(){
  const norm = s => s.replace(/\s+/g, ' ').trim();
  const esc = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const exact = new Map(), pats = [];
  const NUM = String.raw`([−+-]?৳?[০-৯0-9][০-৯0-9.,]*(?:\s*(?:মণ|কেজি|টন|কিমি|ঘণ্টা|দিন|মিনিট|%|maunds?|kg|km|t|hours?|days?|min))?(?:\s*\([^)]*\))?)`;
  const add = (bn, en) => {
    bn = norm(bn);
    if (!/\{#?\}/.test(bn)) { if (!exact.has(bn)) exact.set(bn, en); return; }
    let i = 0;
    const out = en.replace(/\{(\d*)\}/g, (m, d) => '{' + (d === '' ? i++ : d) + '}');
    /* {} = any value; {#} = a number with an optional unit, so it can sit next to a name */
    const toks = bn.split(/(\{#?\})/), lits = toks.filter((t, k) => k % 2 === 0);
    const key = lits.reduce((a, b) => b.length > a.length ? b : a, '');
    /* two values with nothing between them: the first takes the text, the second is often empty */
    const re = toks.map((t, k) => k % 2 === 0 ? esc(t) : t === '{#}' ? NUM
      : toks[k + 1] === '' && toks[k + 2] ? '(.+)' : toks[k - 1] === '' && k > 1 ? '(.*?)' : '(.+?)').join('');
    pats.push({re: new RegExp('^' + re + '$'), key: key.trim(), en: out});
  };
  for (const [bn, en] of I18N_CATALOG) {
    add(bn, en);
    /* an icon or element at either end is not part of the text node: also match without it */
    if (/^\{\} /.test(bn) && /^\{\} /.test(en) && !/\{\d\}/.test(en)) add(bn.slice(3), en.slice(3));
    if (/\{\}$/.test(bn) && /\{\}$/.test(en) && !/\{\d\}/.test(en)) add(bn.slice(0, -2), en.slice(0, -2));
  }
  pats.sort((a, b) => b.key.length - a.key.length);
  I18N_CAT = {exact, pats, norm};
})();

